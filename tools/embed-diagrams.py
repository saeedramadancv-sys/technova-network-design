"""Embed the Mermaid sources into README.md so GitHub renders them.

GitHub draws Mermaid only inside a ```mermaid fence in a Markdown file. A
standalone .mmd file is shown as plain text, so the topology - the one thing a
reader wants to see first - is invisible on the repository page.

The .mmd files stay the source of truth. This script copies them into README.md
between the DIAGRAMS markers, which means the two can be brought back into step
with one command instead of being edited twice and quietly diverging.

    python tools/embed-diagrams.py          # rewrite the README block
    python tools/embed-diagrams.py --check  # exit 1 if it is out of date
"""
import sys
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
README = ROOT / "README.md"

START = "<!-- DIAGRAMS:START - generated by tools/embed-diagrams.py, do not edit by hand -->"
END = "<!-- DIAGRAMS:END -->"

# Order matters: this is the order a reader should meet them in.
DIAGRAMS = [
    ("logical-topology.mmd", "Logical topology", "Sites, devices and the addressing each one carries."),
    ("ospf-areas.mmd", "OSPF areas and summarisation", "Why the backbone carries two branch routes instead of eight."),
    ("physical-topology.mmd", "Physical topology", "Ports and cable types, as built in Packet Tracer."),
]


def build() -> str:
    parts = [START, ""]

    for filename, title, caption in DIAGRAMS:
        source = (ROOT / "diagrams" / filename).read_text(encoding="utf-8").strip()
        parts += [
            f"### {title}",
            "",
            f"{caption}",
            "",
            "```mermaid",
            source,
            "```",
            "",
            f"<sub>Source: [`diagrams/{filename}`](diagrams/{filename})</sub>",
            "",
        ]

    parts.append(END)
    return "\n".join(parts)


def main() -> int:
    readme = README.read_text(encoding="utf-8")

    if START not in readme or END not in readme:
        print("README.md is missing the DIAGRAMS markers.", file=sys.stderr)
        return 2

    before = readme[: readme.index(START)]
    after = readme[readme.index(END) + len(END) :]
    updated = before + build() + after

    if "--check" in sys.argv:
        if updated != readme:
            print("README diagrams are out of date. Run: python tools/embed-diagrams.py", file=sys.stderr)
            return 1
        print("README diagrams match diagrams/*.mmd")
        return 0

    README.write_text(updated, encoding="utf-8")
    print(f"Embedded {len(DIAGRAMS)} diagram(s) into README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
